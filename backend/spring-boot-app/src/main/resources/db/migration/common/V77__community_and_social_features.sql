CREATE TABLE community_activities (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 circle_id BIGINT NOT NULL REFERENCES circles(id) ON DELETE CASCADE,
 author_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 kind VARCHAR(5) NOT NULL CHECK(kind IN ('POLL','EVENT')),
 title VARCHAR(200) NOT NULL,
 details VARCHAR(2000) NOT NULL DEFAULT '',
 location VARCHAR(300) NOT NULL DEFAULT '',
 starts_at TIMESTAMP WITH TIME ZONE,
 ends_at TIMESTAMP WITH TIME ZONE,
 multiple BOOLEAN NOT NULL DEFAULT FALSE,
 closed BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_community_activities_circle ON community_activities(circle_id,id);
CREATE TABLE community_poll_options (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 activity_id BIGINT NOT NULL REFERENCES community_activities(id) ON DELETE CASCADE,
 label VARCHAR(150) NOT NULL,
 UNIQUE(activity_id,id)
);
CREATE TABLE community_poll_votes (
 activity_id BIGINT NOT NULL,
 option_id BIGINT NOT NULL,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 PRIMARY KEY(option_id,user_id),
 FOREIGN KEY(activity_id,option_id) REFERENCES community_poll_options(activity_id,id) ON DELETE CASCADE
);
CREATE TABLE community_event_rsvps (
 activity_id BIGINT NOT NULL REFERENCES community_activities(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 response VARCHAR(5) NOT NULL CHECK(response IN ('YES','NO','MAYBE')),
 PRIMARY KEY(activity_id,user_id)
);
CREATE TABLE social_close_friends (
 owner_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 member_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 PRIMARY KEY(owner_user_id,member_user_id),
 CHECK(owner_user_id<>member_user_id)
);
