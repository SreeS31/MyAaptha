CREATE TABLE advisor_categories (
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 category_key VARCHAR(80) NOT NULL,
 name VARCHAR(100) NOT NULL,
 PRIMARY KEY(user_id,category_key)
);
CREATE TABLE advisor_people (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 identity_key VARCHAR(100) NOT NULL,
 kind VARCHAR(10) NOT NULL CHECK(kind IN ('MEMBER','CONTACT','EXTERNAL')),
 member_user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
 contact_id BIGINT REFERENCES address_book_contacts(id) ON DELETE CASCADE,
 details TEXT NOT NULL,
 follow_posts BOOLEAN NOT NULL DEFAULT FALSE,
 version BIGINT NOT NULL DEFAULT 1,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(user_id,identity_key),
 UNIQUE(user_id,id),
 CHECK((kind='MEMBER' AND member_user_id IS NOT NULL AND contact_id IS NULL) OR (kind='CONTACT' AND contact_id IS NOT NULL AND member_user_id IS NULL) OR (kind='EXTERNAL' AND member_user_id IS NULL AND contact_id IS NULL))
);
CREATE INDEX idx_advisor_people_owner ON advisor_people(user_id,id);
CREATE TABLE advisor_category_members (
 user_id BIGINT NOT NULL,
 advisor_id BIGINT NOT NULL,
 category_key VARCHAR(80) NOT NULL,
 PRIMARY KEY(advisor_id,category_key),
 FOREIGN KEY(user_id,advisor_id) REFERENCES advisor_people(user_id,id) ON DELETE CASCADE,
 FOREIGN KEY(user_id,category_key) REFERENCES advisor_categories(user_id,category_key) ON DELETE CASCADE
);
CREATE TABLE social_reposts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 post_id BIGINT NOT NULL REFERENCES social_posts(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(post_id,user_id)
);
CREATE INDEX idx_social_reposts_recent ON social_reposts(created_at,id);
CREATE INDEX idx_social_reposts_user ON social_reposts(user_id,created_at,id);
