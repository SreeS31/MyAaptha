CREATE TABLE communication_calls (
 id VARCHAR(36) PRIMARY KEY,
 scope VARCHAR(10) NOT NULL CHECK (scope IN ('DIRECT','CIRCLE')),
 target_id BIGINT NOT NULL,
 creator_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 call_type VARCHAR(5) NOT NULL CHECK (call_type IN ('AUDIO','VIDEO')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 ended_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_communication_calls_active ON communication_calls(scope,target_id,created_at);
CREATE TABLE communication_call_members (
 call_id VARCHAR(36) NOT NULL REFERENCES communication_calls(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 status VARCHAR(10) NOT NULL CHECK (status IN ('INVITED','JOINED','LEFT','DECLINED')),
 last_seen TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(call_id,user_id)
);
CREATE TABLE communication_call_signals (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 call_id VARCHAR(36) NOT NULL REFERENCES communication_calls(id) ON DELETE CASCADE,
 sender_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 recipient_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 signal_type VARCHAR(10) NOT NULL CHECK (signal_type IN ('offer','answer','ice')),
 payload TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_communication_signals_recipient ON communication_call_signals(call_id,recipient_user_id,id);
CREATE INDEX idx_communication_signals_expiry ON communication_call_signals(created_at);
