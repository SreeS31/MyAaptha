CREATE TABLE people_highlight_preferences (
 user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE people_highlights (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 target_key VARCHAR(40) NOT NULL,
 member_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
 contact_id BIGINT REFERENCES address_book_contacts(id) ON DELETE CASCADE,
 starred BOOLEAN NOT NULL DEFAULT FALSE,
 hidden BOOLEAN NOT NULL DEFAULT FALSE,
 UNIQUE(user_id,target_key),
 CHECK((member_id IS NOT NULL AND contact_id IS NULL) OR (contact_id IS NOT NULL AND member_id IS NULL))
);
CREATE INDEX idx_people_highlights_owner ON people_highlights(user_id,id);
CREATE TABLE advisor_external_sources (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 advisor_id BIGINT NOT NULL,
 url_hash VARCHAR(64) NOT NULL,
 source_data TEXT NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 last_attempt TIMESTAMP WITH TIME ZONE,
 last_success TIMESTAMP WITH TIME ZONE,
 last_error VARCHAR(160),
 UNIQUE(user_id,advisor_id,url_hash),
 UNIQUE(user_id,id),
 FOREIGN KEY(user_id,advisor_id) REFERENCES advisor_people(user_id,id) ON DELETE CASCADE
);
CREATE TABLE advisor_external_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL,
 source_id BIGINT NOT NULL,
 item_key VARCHAR(64) NOT NULL,
 item_data TEXT NOT NULL,
 saved BOOLEAN NOT NULL DEFAULT FALSE,
 liked BOOLEAN NOT NULL DEFAULT FALSE,
 imported_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(source_id,item_key),
 FOREIGN KEY(user_id,source_id) REFERENCES advisor_external_sources(user_id,id) ON DELETE CASCADE
);
CREATE INDEX idx_advisor_external_items_owner ON advisor_external_items(user_id,id);
