CREATE TABLE security_incidents (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
 category VARCHAR(40) NOT NULL,
 summary VARCHAR(300) NOT NULL,
 request_path VARCHAR(300) NOT NULL,
 ip_address VARCHAR(64) NOT NULL,
 actor VARCHAR(80),
 blocked_until TIMESTAMP WITH TIME ZONE,
 resolved_at TIMESTAMP WITH TIME ZONE,
 email_status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
 email_attempts INTEGER NOT NULL DEFAULT 0,
 email_next_attempt TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_security_incidents_recent ON security_incidents(occurred_at DESC);
CREATE INDEX idx_security_incidents_email ON security_incidents(email_status,email_next_attempt);
