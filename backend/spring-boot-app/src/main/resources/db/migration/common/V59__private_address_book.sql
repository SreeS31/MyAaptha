CREATE TABLE address_book_contacts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  fingerprint VARCHAR(64) NOT NULL,
  display_name VARCHAR(200) NOT NULL,
  contact_data TEXT NOT NULL,
  source VARCHAR(20) NOT NULL,
  relationship_id BIGINT REFERENCES relationships(id) ON DELETE SET NULL,
  circles_reviewed BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(user_id, fingerprint)
);
CREATE INDEX idx_address_book_owner_cursor ON address_book_contacts(user_id, id);
CREATE TABLE address_book_circle_contacts (
  contact_id BIGINT NOT NULL REFERENCES address_book_contacts(id) ON DELETE CASCADE,
  circle_id BIGINT NOT NULL REFERENCES circles(id) ON DELETE CASCADE,
  PRIMARY KEY(contact_id,circle_id)
);
CREATE INDEX idx_address_circle_contacts ON address_book_circle_contacts(circle_id,contact_id);
