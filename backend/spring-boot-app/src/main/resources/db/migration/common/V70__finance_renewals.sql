CREATE TABLE finance_renewals (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 kind VARCHAR(20) NOT NULL CHECK (kind IN ('BILL','WARRANTY','SERVICE')),
 title VARCHAR(160) NOT NULL,
 provider VARCHAR(160),
 reference_number VARCHAR(160),
 amount NUMERIC(16,2),
 purchased_on DATE,
 expires_on DATE NOT NULL,
 timezone VARCHAR(80) NOT NULL,
 notes VARCHAR(2000),
 reminders_enabled BOOLEAN NOT NULL DEFAULT TRUE,
 archived BOOLEAN NOT NULL DEFAULT FALSE,
 cycle INTEGER NOT NULL DEFAULT 1,
 next_reminder_at TIMESTAMP,
 attachment_key VARCHAR(700),
 attachment_name VARCHAR(255),
 attachment_type VARCHAR(150),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_finance_renewals_owner ON finance_renewals(user_id, expires_on, id);
CREATE INDEX idx_finance_renewals_due ON finance_renewals(next_reminder_at, id);
CREATE TABLE finance_renewal_notices (
 renewal_id BIGINT NOT NULL REFERENCES finance_renewals(id) ON DELETE CASCADE,
 cycle INTEGER NOT NULL,
 reminder_days INTEGER NOT NULL CHECK (reminder_days IN (30,15,7,3,1)),
 notification_id BIGINT NOT NULL REFERENCES notifications(id) ON DELETE CASCADE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (renewal_id, cycle, reminder_days)
);
CREATE INDEX idx_finance_renewal_notice_notification ON finance_renewal_notices(notification_id);
