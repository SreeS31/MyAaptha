package com.myaaptha.platform.security;

import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.config.YamlPropertiesFactoryBean;
import org.springframework.core.io.ClassPathResource;
import static org.assertj.core.api.Assertions.*;

class H2ConstraintConnectionTest {
    @Test
    void checkConstraintsSurviveTheCreatingConnectionAndStillRejectInvalidValues() throws Exception {
        var yaml = new YamlPropertiesFactoryBean();
        yaml.setResources(new ClassPathResource("application.yml"));
        String url = yaml.getObject().getProperty("spring.datasource.url")
                .replace("${random.uuid}", UUID.randomUUID().toString());
        try {
            try (var connection = DriverManager.getConnection(url, "sa", "");
                 var statement = connection.createStatement()) {
                statement.execute("CREATE TABLE constraint_probe (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, audience VARCHAR(20) CHECK (audience IN ('PRIVATE','PUBLIC','CIRCLE')))");
            }
            try (var connection = DriverManager.getConnection(url, "sa", "");
                 var statement = connection.createStatement()) {
                assertThat(statement.executeUpdate("INSERT INTO constraint_probe(audience) VALUES ('PRIVATE')")).isEqualTo(1);
                assertThatThrownBy(() -> statement.executeUpdate("INSERT INTO constraint_probe(audience) VALUES ('INVALID')"))
                        .isInstanceOf(SQLException.class)
                        .satisfies(error -> assertThat(((SQLException) error).getSQLState()).isEqualTo("23513"));
            }
        } finally {
            try (var connection = DriverManager.getConnection(url, "sa", "");
                 var statement = connection.createStatement()) {
                statement.execute("SHUTDOWN");
            }
        }
    }
}
