import {expect,test} from './fixtures';
import {randomUUID} from 'node:crypto';

test.use({actionTimeout:15_000});

test('direct messaging supports private saves, receipts, chat management and forwarding',async({page,playwright})=>{
  test.setTimeout(180_000);
  const api=await playwright.request.newContext({baseURL:'http://127.0.0.1:8080'});
  async function authPost(path:string,data:Record<string,unknown>){
    let response=await api.post(path,{data});
    if(response.status()===429){const wait=Math.min(65,Number(response.headers()['retry-after']||60));await new Promise(resolve=>setTimeout(resolve,(wait+1)*1000));response=await api.post(path,{data});}
    return response;
  }
  async function member(){const username=`msg-${randomUUID().slice(0,10)}`,password=`Message-${randomUUID()}`;
    const created=await authPost('/api/users',{username,password,phoneNumber:`+1888${String(Math.floor(Math.random()*1e10)).padStart(10,'0')}`});expect(created.status()).toBe(200);
    const user=await created.json();const logged=await authPost('/api/auth/login',{identifier:username,password});expect(logged.status()).toBe(200);
    return {...user,username,password,headers:{Authorization:`Bearer ${(await logged.json()).accessToken}`}};
  }
  const sender=await member(),recipient=await member();
  const related=await api.post('/api/network/relationships',{headers:sender.headers,data:{relatedUserId:recipient.id,type:'Friend',visibilityScope:'FRIENDS'}});expect(related.status()).toBe(200);
  const sent=await api.post(`/api/network/messages/with/${recipient.id}`,{headers:sender.headers,multipart:{message:'Important older message'}});expect(sent.status()).toBe(200);const original=await sent.json();expect(original.deliveredAt).toBeNull();
  await api.post(`/api/network/messages/with/${recipient.id}`,{headers:sender.headers,multipart:{message:'Latest message'}});
  await page.goto('/auth');await page.getByLabel('Username or mobile number',{exact:true}).fill(sender.username);await page.getByLabel('Password',{exact:true}).fill(sender.password);await page.getByRole('button',{name:'Continue',exact:true}).click();await expect(page).toHaveURL(/dashboard/);
  await page.goto(`/dashboard?messageUserId=${recipient.id}`);
  const older=page.locator('.direct-chat-message').filter({hasText:'Important older message'});
  await older.getByLabel(`Actions for message ${original.id}`).click();
  expect((await page.getByRole('textbox',{name:'Message text',exact:true}).boundingBox())?.height).toBeLessThanOrEqual(40);
  const menu=page.getByRole('menu',{name:'Message actions',exact:true});
  await expect(menu).toBeVisible();
  expect((await menu.boundingBox())?.width).toBeLessThanOrEqual(220);
  await menu.getByRole('menuitem',{name:'Info',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'Message info'})).toBeVisible();
  await page.getByRole('dialog',{name:'Message info'}).getByRole('button',{name:'Close',exact:true}).click();
  await older.getByLabel(`Actions for message ${original.id}`).click();
  await menu.getByRole('menuitem',{name:'Delete',exact:true}).click();
  await expect(page.getByRole('menuitem',{name:'Delete for me',exact:true})).toBeVisible();
  await expect(page.getByRole('menuitem',{name:'Delete for all',exact:true})).toBeVisible();
  await page.keyboard.press('Escape');
  await older.getByLabel(`Actions for message ${original.id}`).click();
  await menu.getByRole('menuitem',{name:'Star',exact:true}).click();await expect(older.getByLabel('Starred',{exact:true})).toBeVisible();
  await older.getByLabel(`Actions for message ${original.id}`).click();
  await menu.getByRole('menuitem',{name:'Pin for me',exact:true}).click();await expect(older.getByLabel('Pinned for me',{exact:true})).toBeVisible();
  await page.getByLabel('Show messages',{exact:true}).selectOption('starred');await expect(page.locator('.direct-chat-message')).toHaveCount(1);
  await page.screenshot({path:`../../.tools/preview/messages-${test.info().project.name}.png`,fullPage:true});
  const other=await api.get(`/api/network/messages/with/${sender.id}/saved?kind=starred`,{headers:recipient.headers});expect(await other.json()).toEqual([]);
  // Opening the recipient's visible chat, rather than an API read alone, sends the read receipt.
  await page.goto('/auth');
  await page.evaluate(()=>localStorage.clear());
  const recipientLogin=await page.request.post('/api/web-auth/login',{headers:{'X-MyAaptha-Web':'1','Origin':'http://localhost:3000'},data:{identifier:recipient.username,password:recipient.password}});
  expect(recipientLogin.status()).toBe(200);
  const timing=await recipientLogin.json();
  await page.evaluate(value=>localStorage.setItem('myaaptha.web-session.metadata',JSON.stringify({...value,receivedAtEpochMs:Date.now(),expiresAtEpochMs:Date.now()+value.expiresIn*1000})),timing);
  await page.goto(`/dashboard?messageUserId=${sender.id}`);await page.bringToFront();
  await expect(page.locator('.direct-chat-message').filter({hasText:'Important older message'})).toBeVisible();
  await expect.poll(async()=>{const response=await api.get(`/api/network/messages/with/${recipient.id}`,{headers:sender.headers});return (await response.json()).find((m:{id:number})=>m.id===original.id).readAt;}).not.toBeNull();
  const senderLogin=await page.request.post('/api/web-auth/login',{headers:{'X-MyAaptha-Web':'1','Origin':'http://localhost:3000'},data:{identifier:sender.username,password:sender.password}});expect(senderLogin.status()).toBe(200);
  await page.goto('/messages');
  const chat=page.locator('.chat-inbox-row').filter({hasText:recipient.username});
  await chat.getByLabel(`More actions for ${recipient.username}`).click();
  await chat.getByRole('button',{name:'Pin chat',exact:true}).click();
  await expect(chat.getByRole('button',{name:'Unpin chat',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Conversation settings',exact:true}).click();
  await page.getByRole('checkbox',{name:'Share read receipts'}).click();
  await expect.poll(async()=>{const value=await api.get('/api/network/messages/preferences',{headers:sender.headers});return (await value.json()).readReceipts;}).toBe(false);
  await expect(page.getByRole('checkbox',{name:'Share read receipts'})).not.toBeChecked();
  await page.getByRole('dialog',{name:'Conversation settings'}).getByRole('button',{name:'Close',exact:true}).click();
  // Chat settings are shared by clients, but private to their owner.
  if(!(await chat.locator('details').evaluate(element=>element.hasAttribute('open'))))await chat.getByLabel(`More actions for ${recipient.username}`).click();
  await chat.getByRole('button',{name:'Mute',exact:true}).click();
  await expect(chat.getByRole('button',{name:'Unmute',exact:true})).toBeVisible();
  await chat.getByRole('button',{name:'Mark unread',exact:true}).click();
  await expect(chat.getByRole('button',{name:'Clear unread reminder',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Unread',exact:true}).click();await expect(chat).toBeVisible();
  if(!(await chat.locator('details').evaluate(element=>element.hasAttribute('open'))))await chat.getByLabel(`More actions for ${recipient.username}`).click();
  await chat.getByRole('button',{name:'Archive',exact:true}).click();await expect(chat).toHaveCount(0);
  await page.getByRole('button',{name:'Archived',exact:true}).click();
  const archived=page.locator('.chat-inbox-row').filter({hasText:recipient.username});
  await expect(archived).toBeVisible();
  await page.screenshot({path:`../../.tools/preview/chat-settings-${test.info().project.name}.png`,fullPage:true});
  await page.reload();await page.getByRole('button',{name:'Archived',exact:true}).click();
  await archived.getByLabel(`More actions for ${recipient.username}`).click();
  await expect(archived.getByRole('button',{name:'Unmute',exact:true})).toBeVisible();
  await archived.getByRole('button',{name:'Unarchive',exact:true}).click();
  await page.getByRole('button',{name:'All',exact:true}).click();await expect(chat).toBeVisible();
  await page.goto(`/dashboard?messageUserId=${recipient.id}`);
  const originalRow=page.locator('.direct-chat-message').filter({hasText:'Important older message'}).first();
  await originalRow.getByLabel(`Actions for message ${original.id}`).click();
  await menu.getByRole('menuitem',{name:'Forward',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'Forward message',exact:true})).toBeVisible();
  await page.getByRole('checkbox',{name:new RegExp(`^${recipient.username} Person$`,'i')}).check();
  await page.screenshot({path:`../../.tools/preview/forward-message-${test.info().project.name}.png`,fullPage:true});
  await page.getByRole('button',{name:'Send forward',exact:true}).click();
  await expect(originalRow.getByRole('status')).toHaveText('Message forwarded.');
  await expect.poll(async()=>{const response=await api.get(`/api/network/messages/with/${recipient.id}`,{headers:sender.headers});return (await response.json()).filter((m:{forwarded:boolean})=>m.forwarded).length;}).toBe(1);
  await originalRow.getByLabel(`Actions for message ${original.id}`).click();
  await menu.getByRole('menuitem',{name:'Delete',exact:true}).click();
  await expect(page.getByRole('menuitem',{name:'Delete for all',exact:true})).toHaveCount(0);
  await page.getByRole('menuitem',{name:'Delete for me',exact:true}).click();
  await expect(page.locator(`[data-message-id="${original.id}"]`)).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('dialog',{name:new RegExp(`^Private conversation with ${recipient.username}$`,'i')})).toBeVisible();
  await expect(page.locator(`[data-message-id="${original.id}"]`)).toHaveCount(0);
  const retained=await api.get(`/api/network/messages/with/${sender.id}`,{headers:recipient.headers});
  expect((await retained.json()).find((m:{id:number})=>m.id===original.id).message).toBe('Important older message');
  const fresh=await api.post(`/api/network/messages/with/${recipient.id}`,{headers:sender.headers,multipart:{message:'Fresh message to delete for all'}});
  expect(fresh.status()).toBe(200);const freshMessage=await fresh.json();
  await page.reload();const freshRow=page.locator(`[data-message-id="${freshMessage.id}"]`);
  await freshRow.getByLabel(`Actions for message ${freshMessage.id}`).click();
  await menu.getByRole('menuitem',{name:'Delete',exact:true}).click();
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('menuitem',{name:'Delete for all',exact:true}).click();
  await expect(freshRow).toContainText('This message was deleted');
  await api.dispose();
});
