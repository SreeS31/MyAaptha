import argparse,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
TARGET=ROOT/'mobile/flutter-app/lib/features/shell/presentation/interest_catalog.dart'
def generated():
 source=(ROOT/'frontend/nextjs-app/app/lib/interests-catalog.ts').read_text(encoding='utf-8-sig')
 categories={name:values.split('|') for name,values in re.findall(r"'([^']+)': '([^']+)'[.]split",source)}
 if not categories:raise ValueError('No interest catalogue categories found')
 return '// Generated by infrastructure/sync_interest_catalog.py from the web catalogue.\nconst interestCategories = <String,List<String>>'+json.dumps(categories,ensure_ascii=True,indent=2)+';\nfinal allInterests = interestCategories.values.expand((v)=>v).toSet().toList()..sort();\n'
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
 content=generated()
 if args.check:
  if not TARGET.is_file() or TARGET.read_text(encoding='utf-8')!=content:raise SystemExit('Native interest catalogue is out of sync')
 else:TARGET.write_text(content,encoding='utf-8')
